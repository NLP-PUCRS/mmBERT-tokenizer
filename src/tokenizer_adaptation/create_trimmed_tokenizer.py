import torch
import json
import os
import re
import gc
from transformers import AutoTokenizer, AutoModelForMaskedLM, PreTrainedTokenizerFast, PreTrainedModel
from collections import Counter
from tqdm import tqdm
from datasets import load_dataset
from typing import Optional
from dotenv import load_dotenv

load_dotenv()
SOURCE_TOKENIZER = os.getenv("SOURCE_TOKENIZER", "jhu-clsp/mmbert-base")
OUTPUT_DIR = os.getenv("OUTPUT_DIR", "models/mmbert_pt_32k")
DATASET_NAME = os.getenv("DATASET_NAME", "wikimedia/wikipedia")
DATASET_CONFIG = os.getenv("DATASET_CONFIG", "20231101.pt")
HF_TOKEN = os.getenv("HF_TOKEN", "")

MAX_VOCAB_SIZE = int(os.getenv("MAX_VOCAB_SIZE", "32768"))
SAMPLE_SIZE = int(os.getenv("SAMPLE_SIZE", "110000"))
MIN_FREQ = int(os.getenv("MIN_FREQ", "2"))

# Define the Regex for foreign scripts to keep Latin and basic symbols
NON_LATIN_PATTERN = re.compile(r'[^\u0000-\u017F\u2000-\u206F\u2581]')

def load_original_model_and_tokenizer(model_name: str) -> tuple[PreTrainedTokenizerFast, PreTrainedModel, torch.Tensor, dict[str, int]]:
    """Loads the base tokenizer and model and extracts initial embeddings and vocabulary."""
    print("Step 1: Loading original model and tokenizer...")
    tokenizer = AutoTokenizer.from_pretrained(model_name, use_fast=True)
    model = AutoModelForMaskedLM.from_pretrained(model_name)
    old_embeddings = model.get_input_embeddings().weight.data
    old_vocab = tokenizer.get_vocab()
    return tokenizer, model, old_embeddings, old_vocab

def analyze_corpus(tokenizer: PreTrainedTokenizerFast, dataset_name: str, dataset_config: str, sample_size: int, hf_token: Optional[str] = None) -> Counter:
    """Streams the dataset to count frequencies of tokens generated by the original tokenizer."""
    print(f"Step 2: Analyzing corpus ({dataset_name})...")
    dataset = load_dataset(dataset_name, dataset_config, split="train", streaming=True, token=hf_token)
    dataset = dataset.take(sample_size)

    token_counts = Counter()
    for item in tqdm(dataset, desc="Tokenizing"):
        tokens = tokenizer.tokenize(item["text"])
        token_counts.update(tokens)
    return token_counts

def filter_and_select_tokens(old_vocab: dict[str, int], token_counts: Counter, max_vocab_size: int, min_freq: int, tokenizer: PreTrainedTokenizerFast) -> tuple[set[str], set[str]]:
    """Selects top-K tokens from the corpus while preserving special tokens and base Latin characters."""
    print("Step 3: Lexical Denoising, Filtering, and Top-K Truncation...")
    final_keep_tokens = set()
    script_rejected_tokens = set()

    # 1. PRESERVE SPECIAL TOKENS
    special_tokens_set = set()
    for hidden_special in ["<unk>", "<s>", "</s>", "<pad>", "<mask>", "<cls>", "<sep>"]:
        if hidden_special in old_vocab:
            special_tokens_set.add(hidden_special)
    for special in tokenizer.all_special_tokens:
        special_tokens_set.add(special)

    final_keep_tokens.update(special_tokens_set)

    # 2. PRESERVE BASE BYTES (Latin scripts)
    for tok in old_vocab.keys():
        if len(tok) <= 2:
            if NON_LATIN_PATTERN.search(tok):
                script_rejected_tokens.add(tok)
                continue
            final_keep_tokens.add(tok)

    slots_available = max_vocab_size - len(final_keep_tokens)

    # 3. SELECT CORPUS TOKENS (Ranked by frequency)
    sorted_corpus_tokens = sorted(token_counts.items(), key=lambda x: x[1], reverse=True)

    for tok, freq in sorted_corpus_tokens:
        if tok in final_keep_tokens:
            continue
        if NON_LATIN_PATTERN.search(tok):
            script_rejected_tokens.add(tok)
            continue
        if freq < min_freq:
            continue

        if slots_available > 0 and tok.strip():
            final_keep_tokens.add(tok)
            slots_available -= 1

    return final_keep_tokens, special_tokens_set

def align_weights_and_reorder_vocab(final_keep_tokens: set[str], special_tokens_set: set[str], old_vocab: dict[str, int], old_embeddings: torch.Tensor, token_counts: Counter, tokenizer: PreTrainedTokenizerFast, output_dir: str) -> tuple[dict[str, int], list[torch.Tensor]]:
    """Reconstructs the tokenizer JSON with the new vocabulary and aligns weights to the new IDs."""
    print("Step 4: Aligning weights and reordering BPE JSON by frequency...")
    new_vocab = {}
    new_weights = []
    new_id = 0

    # Sort tokens to keep special ones first and others by frequency
    special_ordered = sorted([t for t in final_keep_tokens if t in special_tokens_set],
                             key=lambda x: old_vocab.get(x, 999999))
    regular_tokens = [t for t in final_keep_tokens if t not in special_tokens_set]
    regular_ordered = sorted(regular_tokens,
                             key=lambda x: (-token_counts.get(x, 0), old_vocab.get(x, 999999)))

    ordered_final_tokens = special_ordered + regular_ordered

    for token in ordered_final_tokens:
        old_id = old_vocab[token]
        new_vocab[token] = new_id
        new_weights.append(old_embeddings[old_id])
        new_id += 1

    tok_json = json.loads(tokenizer.backend_tokenizer.to_str())
    tok_json["model"]["vocab"] = new_vocab

    # Update merge rules to remove rules involving deleted tokens
    if "merges" in tok_json["model"]:
        old_merges = tok_json["model"]["merges"]
        new_merges = []
        for merge_rule in old_merges:
            if isinstance(merge_rule, list) and len(merge_rule) == 2:
                part1, part2 = merge_rule
            elif isinstance(merge_rule, str):
                parts = merge_rule.split(" ")
                if len(parts) == 2:
                    part1, part2 = parts
                else:
                    continue
            else:
                continue

            combined = part1 + part2
            if part1 in new_vocab and part2 in new_vocab and combined in new_vocab:
                new_merges.append(merge_rule)
        tok_json["model"]["merges"] = new_merges

    os.makedirs(output_dir, exist_ok=True)
    tokenizer.save_pretrained(output_dir)

    # Clean added_tokens to ensure ID consistency
    if "added_tokens" in tok_json:
        valid_added_tokens = []
        for t in tok_json["added_tokens"]:
            if t["content"] in new_vocab:
                t["id"] = new_vocab[t["content"]]
                valid_added_tokens.append(t)
        tok_json["added_tokens"] = valid_added_tokens

    # Overwrite the saved tokenizer.json with the cleaned version
    with open(os.path.join(output_dir, "tokenizer.json"), "w", encoding="utf-8") as f:
        json.dump(tok_json, f, ensure_ascii=False)

    added_tokens_path = os.path.join(output_dir, "added_tokens.json")
    if os.path.exists(added_tokens_path):
        os.remove(added_tokens_path)

    # Clean up tokenizer_config to remove references to deleted added tokens
    config_path = os.path.join(output_dir, "tokenizer_config.json")
    if os.path.exists(config_path):
        with open(config_path, "r", encoding="utf-8") as f:
            t_config = json.load(f)

        t_config.pop("added_tokens_decoder", None)

        with open(config_path, "w", encoding="utf-8") as f:
            json.dump(t_config, f, ensure_ascii=False, indent=2)

    return new_vocab, new_weights

def update_and_save_model(output_dir: str, model: PreTrainedModel, new_vocab: dict[str, int], new_weights: list[torch.Tensor], tokenizer: PreTrainedTokenizerFast) -> None:
    """Resizes model embeddings, initializes them with aligned weights, and saves the final model."""
    print("Step 5: Updating model architecture and saving...")
    new_tokenizer = AutoTokenizer.from_pretrained(output_dir)
    new_weight_tensor = torch.stack(new_weights)

    model.resize_token_embeddings(len(new_vocab))
    model.get_input_embeddings().weight.data = new_weight_tensor

    # Update config token IDs to match the new vocabulary
    if model.config.pad_token_id is not None and new_tokenizer.pad_token in new_vocab:
        model.config.pad_token_id = new_vocab[new_tokenizer.pad_token]
    if model.config.bos_token_id is not None and new_tokenizer.bos_token in new_vocab:
        model.config.bos_token_id = new_vocab[new_tokenizer.bos_token]
    if model.config.eos_token_id is not None and new_tokenizer.eos_token in new_vocab:
        model.config.eos_token_id = new_vocab[new_tokenizer.eos_token]

    new_tokenizer.save_pretrained(output_dir)
    model.save_pretrained(output_dir)

def main() -> None:
    """Executes the full tokenizer trimming and model adaptation pipeline."""
    # Load original model and tokenizer
    tokenizer, model, old_embeddings, old_vocab = load_original_model_and_tokenizer(SOURCE_TOKENIZER)

    # Analyze corpus
    token_counts = analyze_corpus(tokenizer, DATASET_NAME, DATASET_CONFIG, SAMPLE_SIZE, HF_TOKEN)

    # Filter and select tokens
    final_keep_tokens, special_tokens_set = filter_and_select_tokens(old_vocab, token_counts, MAX_VOCAB_SIZE, MIN_FREQ, tokenizer)

    # Align weights and reorder vocab
    new_vocab, new_weights = align_weights_and_reorder_vocab(final_keep_tokens, special_tokens_set, old_vocab, old_embeddings, token_counts, tokenizer, OUTPUT_DIR)

    # Update and save model
    update_and_save_model(OUTPUT_DIR, model, new_vocab, new_weights, tokenizer)

    gc.collect()

    print(f"Original Vocab Size: {len(old_vocab)}")
    print(f"New Vocab Size: {len(new_vocab)} (Capped at {MAX_VOCAB_SIZE})")
    print(f"Saved to: {OUTPUT_DIR}")

if __name__ == "__main__":
    main()